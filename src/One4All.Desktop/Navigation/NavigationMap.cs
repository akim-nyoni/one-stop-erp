using One4All.Application.Navigation;

namespace One4All.Desktop.Navigation;

/// <summary>A business module as people know it (Sales, Housing, Payroll…), with its screens in plain-language groups.</summary>
/// <param name="Title">The module's name.</param>
/// <param name="Glyph">Its icon.</param>
/// <param name="Accent">Its colour.</param>
/// <param name="Purpose">One line on what it is for.</param>
/// <param name="Takes">The operations-console modules whose actions not placed below fall into this module's "More" group.</param>
/// <param name="Groups">Its groups, in the order shown.</param>
public sealed record NavModuleSpec(string Title, string Glyph, string Accent, string Purpose, IReadOnlyList<string> Takes, IReadOnlyList<NavGroupSpec> Groups);

/// <summary>A group of screens inside a module (e.g. Housing → Waiting list).</summary>
/// <param name="Title">The group's name.</param>
/// <param name="Items">Its screens, in the order shown.</param>
public sealed record NavGroupSpec(string Title, IReadOnlyList<NavItemSpec> Items);

/// <summary>One screen: an operations-console action (by its console module and title) or a dedicated window (by its key).</summary>
/// <param name="ConsoleModule">The action's console module (also what gates a window by licence and permission; null: always available).</param>
/// <param name="Operation">The action's title, or null for a window.</param>
/// <param name="Window">The window's key, or null for an action.</param>
/// <param name="Title">The name shown (null: the action's own title).</param>
/// <param name="Purpose">What it is for (null: the action's description).</param>
/// <param name="Area">Where it sits in the Maintenance / Transactions / Enquiries / Utilities menus (null: the action's own).</param>
public sealed record NavItemSpec(string? ConsoleModule, string? Operation, string? Window, string? Title, string? Purpose, MenuArea? Area);

