    private static NavItemSpec O(string moduleAndTitle, string? display = null)
    {
        int split = moduleAndTitle.IndexOf(": ", StringComparison.Ordinal);
        return new NavItemSpec(moduleAndTitle[..split], moduleAndTitle[(split + 2)..], null, display, null, null);
    }

    private static NavItemSpec W(string key, string title, string purpose, MenuArea area, string? gate = null) => new(gate, null, key, title, purpose, area);

    private static NavGroupSpec G(string title, params NavItemSpec[] items) => new(title, items);

