using One4All.Core.Common;

namespace One4All.Core.Offline;

/// <summary>The state of a queued offline operation.</summary>
public enum OfflineOperationStatus
{
    /// <summary>Captured and waiting to be replayed to the central database.</summary>
    Pending = 0,

    /// <summary>Successfully replayed.</summary>
    Synced = 1,

    /// <summary>Replay failed too many times; dead-lettered for an operator to inspect.</summary>
    Failed = 2,

    /// <summary>Deliberately abandoned by an operator; kept for audit, never replayed.</summary>
    Discarded = 3,
}

/// <summary>
/// An operation captured on a terminal while it was offline (brief §4.1, offline POS), queued in an
/// outbox to be replayed to the central database when connectivity returns. The <see cref="OperationId"/>
/// is generated by the client at capture time and is the idempotency key: replaying the same operation id
/// must never apply the effect twice. The <see cref="PayloadJson"/> is an opaque, self-describing snapshot
/// that the matching handler (selected by <see cref="Kind"/>) deserializes and applies.
/// </summary>
public sealed class OfflineOperation : Entity, ICompanyScoped
{
    /// <summary>Parameterless constructor for ORM materialization.</summary>
    private OfflineOperation()
    {
        Kind = string.Empty;
        PayloadJson = string.Empty;
    }

    /// <summary>Captures a new pending operation.</summary>
    /// <param name="companyId">The owning company.</param>
    /// <param name="operationId">The client-generated idempotency key.</param>
    /// <param name="kind">The operation kind (selects the replay handler, e.g. <c>PosSale</c>).</param>
    /// <param name="payloadJson">The serialized operation snapshot.</param>
    /// <param name="createdUtc">When the operation was captured on the terminal.</param>
    public OfflineOperation(long companyId, Guid operationId, string kind, string payloadJson, DateTimeOffset createdUtc)
    {
        CompanyId = companyId;
        OperationId = operationId;
        Kind = kind;
        PayloadJson = payloadJson;
        CreatedUtc = createdUtc;
        Status = OfflineOperationStatus.Pending;
    }

    /// <inheritdoc />
    public long CompanyId { get; private set; }

    /// <summary>The client-generated idempotency key.</summary>
    public Guid OperationId { get; private set; }

    /// <summary>The operation kind (selects the replay handler).</summary>
    public string Kind { get; private set; }

    /// <summary>The serialized operation snapshot.</summary>
    public string PayloadJson { get; private set; }

    /// <summary>When the operation was captured on the terminal.</summary>
    public DateTimeOffset CreatedUtc { get; private set; }

    /// <summary>The current status.</summary>
    public OfflineOperationStatus Status { get; private set; }

    /// <summary>How many replay attempts have been made.</summary>
    public int Attempts { get; private set; }

    /// <summary>The last replay error, when one occurred.</summary>
    public string? LastError { get; private set; }

    /// <summary>When the operation was successfully replayed, or null.</summary>
    public DateTimeOffset? SyncedUtc { get; private set; }

    /// <summary>Marks the operation as successfully replayed.</summary>
    /// <param name="syncedUtc">When it was replayed.</param>
    public void MarkSynced(DateTimeOffset syncedUtc)
    {
        Status = OfflineOperationStatus.Synced;
        SyncedUtc = syncedUtc;
        LastError = null;
    }

    /// <summary>
    /// Records a failed replay attempt. The operation stays <see cref="OfflineOperationStatus.Pending"/>
    /// (so it is retried) until <paramref name="maxAttempts"/> is reached, after which it is dead-lettered
    /// as <see cref="OfflineOperationStatus.Failed"/>.
    /// </summary>
    /// <param name="error">The failure detail.</param>
    /// <param name="maxAttempts">The attempt ceiling before dead-lettering.</param>
    public void RecordFailure(string error, int maxAttempts)
    {
        Attempts++;
        LastError = error;
        if (Attempts >= maxAttempts)
        {
            Status = OfflineOperationStatus.Failed;
        }
    }

    /// <summary>Dead-letters the operation immediately (e.g. no handler is registered for its kind).</summary>
    /// <param name="error">The failure detail.</param>
    public void Fail(string error)
    {
        Attempts++;
        LastError = error;
        Status = OfflineOperationStatus.Failed;
    }

    /// <summary>
    /// Returns a dead-lettered operation to the queue for another attempt (e.g. after the operator fixed
    /// the underlying cause). Clears the attempt count and last error. Only a <see cref="OfflineOperationStatus.Failed"/>
    /// operation can be requeued.
    /// </summary>
    /// <returns>True when requeued; false when the operation was not in a failed state.</returns>
    public bool Requeue()
    {
        if (Status != OfflineOperationStatus.Failed)
        {
            return false;
        }

        Status = OfflineOperationStatus.Pending;
        Attempts = 0;
        LastError = null;
        return true;
    }

    /// <summary>
    /// Abandons a dead-lettered operation so it is never replayed (kept for audit). Only a
    /// <see cref="OfflineOperationStatus.Failed"/> operation can be discarded.
    /// </summary>
    /// <returns>True when discarded; false when the operation was not in a failed state.</returns>
    public bool Discard()
    {
        if (Status != OfflineOperationStatus.Failed)
        {
            return false;
        }

        Status = OfflineOperationStatus.Discarded;
        return true;
    }
}
